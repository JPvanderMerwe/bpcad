"""
design/tokens.json -> CSS custom properties and Dart constants.

    python tools/tokens.py            write both exports
    python tools/tokens.py --check    fail if either is stale, write nothing

WHY A BUILD STEP AND NOT TWO HAND-KEPT FILES
--------------------------------------------
Product brief 2.6. Two clients shipping in parallel drift the moment a hex
value exists in two places, and the brief calls a colour that differs between
web and native a bug rather than an inconsistency. Acceptance criterion 10 is
that a token change in the shared source updates both.

--check is what makes that real: tests/test_tokens.py runs it, so a token
edited in the source and not exported is a test failure, not a visual surprise
noticed three screens later.

THE GENERATED FILES ARE NOT EDITED. Both carry a header saying so and naming
this script. That is the only defence against somebody fixing a colour in the
CSS, which then silently disagrees with Dart until a screenshot catches it.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "design" / "tokens.json"
CSS_OUT = ROOT / "bpcad" / "web" / "static" / "tokens.css"
DART_OUT = ROOT / "mobile" / "lib" / "tokens.dart"

BANNER = "GENERATED FROM design/tokens.json - DO NOT EDIT THIS FILE"
REGENERATE = "Change the token there and run: python tools/tokens.py"


def load() -> dict[str, Any]:
    if not SOURCE.is_file():
        raise SystemExit("no token source at %s" % SOURCE)
    return json.loads(SOURCE.read_text())


def _clean(section: dict[str, Any]) -> dict[str, Any]:
    """Drop the $comment keys; they document the source, not the output."""
    return {k: v for k, v in section.items() if not k.startswith("$")}


def _hexes(section: dict[str, Any]) -> dict[str, str]:
    return {k: v["hex"] for k, v in _clean(section).items()}


